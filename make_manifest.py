#!/usr/bin/env python3
"""
Builds cache.appcache for Starry Break Final.
Includes all 12.00-14.00 patchsets and custom UI assets.
"""

import os
import hashlib
from datetime import datetime, timezone

FILES = [
    "index.html",
    "jb.html",
    "style.css",
    "launch.js",
    "img/logo.jpg",
    "img/bg.jpg",
    "jb.js",
    "core.js",
    "mem.js",
    "int64.js",
    "ps4_offsets.js",
    "afterglow.js",
    "patchset-1200.bin",
    "patchset-1202.bin",
    "patchset-1250.bin",
    "patchset-1252.bin",
    "patchset-1300.bin",
    "patchset-1302.bin",
    "patchset-1304.bin",
    "patchset-1350.bin",
    "patchset-1352.bin",
    "patchset-1400.bin",
    "hen.bin",
    "goldhen.bin",
]

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_FILE = os.path.join(BASE_DIR, "cache.appcache")

def sha256_short(filepath):
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()[:32]

def main():
    entries = []
    for rel_path in FILES:
        full_path = os.path.join(BASE_DIR, rel_path.replace("/", os.sep))
        if not os.path.isfile(full_path):
            raise FileNotFoundError(f"Missing required file: {rel_path}")
        h = sha256_short(full_path)
        entries.append(f"{rel_path} #{h}")

    now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    content = [
        "CACHE MANIFEST",
        "# generated by make_manifest.py -- do not edit by hand",
        f"# {now_utc}",
        "",
        *entries,
        "",
        "FALLBACK:",
        "jb.html jb.html",
        "",
        "NETWORK:",
        "*",
        ""
    ]

    manifest_text = "\n".join(content)
    with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
        f.write(manifest_text)

    print(f"Generated {OUT_FILE} with {len(entries)} entries ({len(manifest_text.encode('utf-8'))} bytes).")

if __name__ == "__main__":
    main()
