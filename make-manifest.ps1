# PowerShell AppCache Manifest Generator for Starry Break Final
$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$outFile = Join-Path $scriptDir "cache.appcache"

$files = @(
  "index.html",
  "jb.html",
  "style.css",
  "launch.js",
  "img/logo.jpg",
  "img/bg.jpg",
  "jb.js",
  "core.js",
  "mem.js",
  "int64.js",
  "ps4_offsets.js",
  "afterglow.js",
  "patchset-1200.bin",
  "patchset-1202.bin",
  "patchset-1250.bin",
  "patchset-1252.bin",
  "patchset-1300.bin",
  "patchset-1302.bin",
  "patchset-1304.bin",
  "patchset-1350.bin",
  "patchset-1352.bin",
  "patchset-1400.bin",
  "hen.bin",
  "goldhen.bin"
)

$dateStr = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("CACHE MANIFEST")
$lines.Add("# generated by make-manifest.ps1 -- do not edit by hand")
$lines.Add("# $dateStr")
$lines.Add("")

foreach ($f in $files) {
  $targetPath = Join-Path $scriptDir ($f -replace '/', '\')
  if (-not (Test-Path $targetPath)) {
    throw "Missing required manifest file: $f"
  }
  $hash = (Get-FileHash -Path $targetPath -Algorithm SHA256).Hash.ToLower().Substring(0, 32)
  $lines.Add("$f #$hash")
}

$lines.Add("")
$lines.Add("FALLBACK:")
$lines.Add("jb.html jb.html")
$lines.Add("")
$lines.Add("NETWORK:")
$lines.Add("*")
$lines.Add("")

[System.IO.File]::WriteAllLines($outFile, $lines, [System.Text.Encoding]::UTF8)
Write-Host "Successfully generated cache.appcache with $($files.Count) entries."
