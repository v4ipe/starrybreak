#!/bin/bash
# Builds cache.appcache from the files Starry Break Final actually needs.
set -e
cd "$(dirname "$0")"

OUT=cache.appcache
FILES="index.html jb.html style.css launch.js img/logo.jpg img/bg.jpg
       jb.js core.js mem.js int64.js ps4_offsets.js afterglow.js
       patchset-1200.bin patchset-1202.bin patchset-1250.bin patchset-1252.bin
       patchset-1300.bin patchset-1302.bin patchset-1304.bin patchset-1350.bin
       patchset-1352.bin patchset-1400.bin hen.bin goldhen.bin"

{
  echo "CACHE MANIFEST"
  echo "# generated by make-manifest.sh -- do not edit by hand"
  echo "# $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo
  for f in $FILES; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
    printf '%s #%s\n' "$f" "$(sha256sum "$f" | cut -c1-32)"
  done
  echo
  echo "FALLBACK:"
  echo "jb.html jb.html"
  echo
  echo "NETWORK:"
  echo "*"
} > "$OUT"

echo "$OUT: $(grep -cE '^[^#[:space:]]+ #' "$OUT") entries, $(wc -c < "$OUT") bytes"
